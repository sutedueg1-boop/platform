// كل رد ثابت (مش من بيانات حية) — المصدر "دليل استخدام المنصة" وضوحًا
// إن ده شرح للفيتشر نفسه مش بيانات شخص. مرتبة الأخص أولًا.
'use strict';

const { normalizeArabic } = require('./chatbot-kb');

const ADMIN_TIER = ['super_admin', 'hse_admin', 'dept_admin', 'maint_admin', 'ceo', 'hse_director'];
const isAdmin = role => ADMIN_TIER.includes(role);

const SOURCE = 'دليل استخدام المنصة';

// كل بند: { re, reply(admin) } — reply ممكن تكون نص ثابت أو دالة بتاخد
// isAdminUser عشان ترد بشكل مختلف شوية للإدارة عن العامل.
